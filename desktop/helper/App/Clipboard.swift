import AppKit

/// Full copy of a pasteboard (every item, every type) so the user's clipboard can be put back
/// after we borrow it for ⌘C/⌘V. Kept in memory only.
struct PasteboardSnapshot {
    private let items: [[(NSPasteboard.PasteboardType, Data)]]

    init(_ pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let restored: [NSPasteboardItem] = items.compactMap { pairs in
            guard !pairs.isEmpty else { return nil }
            let item = NSPasteboardItem()
            for (type, data) in pairs { item.setData(data, forType: type) }
            return item
        }
        if !restored.isEmpty { pasteboard.writeObjects(restored) }
    }
}

/// Puts `text` on the pasteboard as plain text, provided lazily so we learn when the target app
/// actually reads it (i.e. consumed the paste) and can restore the user's clipboard right after.
/// Marked transient (nspasteboard.org) so clipboard managers skip it.
final class PasteSource: NSObject, NSPasteboardItemDataProvider {
    private let text: String
    private(set) var firstReadAt: Date?
    var onFirstRead: (() -> Void)?

    init(text: String) {
        self.text = text
    }

    /// Returns the pasteboard changeCount after writing.
    func write(to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setDataProvider(self, forTypes: [.string])
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        item.setString(text, forType: type)
        if firstReadAt == nil {
            firstReadAt = Date()
            onFirstRead?()
        }
    }
}

enum Keys {
    static let c: CGKeyCode = 8
    static let v: CGKeyCode = 9

    /// Posts ⌘+key to the frontmost app (needs Accessibility permission).
    static func postCommand(_ key: CGKeyCode) {
        let source = CGEventSource(stateID: .hidSystemState)
        for isDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: isDown) else { continue }
            event.flags = .maskCommand
            event.post(tap: .cghidEventTap)
        }
    }
}
